"""Generate deploy/k8s/services.yaml from web/scenarios.json.

One source of truth: the topology the dashboard draws is the topology that gets
deployed. Run:  python deploy/gen_manifests.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = json.loads((ROOT / "web" / "scenarios.json").read_text())
ns = spec["namespace"]
IMAGE = "ghcr.io/YOUR_GITHUB_USER/vigil-demo-app"   # replace after you push the image (see README)

# memory limits and cpu per replica come from the same spec the simulator uses
docs = []
for s in spec["services"]:
    name = s["name"]
    downstream = ",".join(f"{c['to']}=http://{c['to']}.{ns}.svc:8080/" for c in s["calls"] if c["critical"])
    docs.append(f"""apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  namespace: {ns}
  annotations:
    kubernetes.io/change-cause: "initial release {s['version']}"
spec:
  replicas: {s['replicas']}
  selector:
    matchLabels: {{app: {name}}}
  template:
    metadata:
      labels: {{app: {name}}}
      annotations:
        prometheus.io/scrape: "true"
        prometheus.io/port: "8080"
        prometheus.io/path: /metrics
    spec:
      containers:
        - name: app
          image: {IMAGE}:{s['version']}
          ports: [{{containerPort: 8080}}]
          env:
            - {{name: SERVICE_NAME, value: {name}}}
            - {{name: BASE_LATENCY_MS, value: "{s['own_ms']}"}}
            - {{name: DOWNSTREAMS, value: "{downstream}"}}
          readinessProbe:
            httpGet: {{path: /healthz, port: 8080}}
            periodSeconds: 3
          resources:
            requests: {{cpu: 50m, memory: {s['mem_limit_mb'] // 2}Mi}}
            limits: {{cpu: 500m, memory: {s['mem_limit_mb']}Mi}}
---
apiVersion: v1
kind: Service
metadata:
  name: {name}
  namespace: {ns}
spec:
  selector: {{app: {name}}}
  ports: [{{port: 8080, targetPort: 8080}}]""")

out = ROOT / "deploy" / "k8s" / "services.yaml"
out.write_text("# Generated by deploy/gen_manifests.py. Do not edit by hand.\n---\n" + "\n---\n".join(docs) + "\n")
print(f"wrote {out.relative_to(ROOT)} ({len(spec['services'])} services)")
